import type { EvalReport } from "./index.ts";

const pct = (n: number, d: number) => (d ? `${((100 * n) / d).toFixed(0)}%` : "n/a");
const usd = (n: number) => `$${n.toFixed(4)}`;

export function renderReport(r: EvalReport): string {
  const done = r.tasks.filter((t) => t.state !== "SKIPPED");
  const resolved = done.filter((t) => t.resolved).length;
  const meanWall = done.length ? done.reduce((s, t) => s + t.wallMs, 0) / done.length / 1000 : 0;
  const traceable = done.filter((t) => t.state === "AWAITING_MERGE_APPROVAL");
  const meanTrace = traceable.length ? traceable.reduce((s, t) => s + t.traceable, 0) / traceable.length : 0;
  const chaosOk = r.chaos.filter((c) => c.crashed && c.resumed).length;
  const fake = r.mode === "fake";
  const lines = [
    "# SAGE — Evaluation",
    "",
    "> Generated by `sage eval` — measured numbers only. Do not edit by hand; re-run `sage eval`.",
    "",
    `- **Mode:** ${r.mode}${fake ? " (deterministic fake engine; scripted agent solutions; zero LLM calls)" : ""}`,
    `- **Model:** ${r.model}`,
    `- **Date:** ${r.date} · **Commit:** \`${r.commit}\` · **Platform:** ${r.platform} · **Bun:** ${r.bun}`,
    "",
    fake
      ? "**How to read fake-mode numbers.** The agent's solutions are scripted, so the resolved rate measures SAGE's " +
        "pipeline (planning → isolated execution → policy → verification → merge → hidden acceptance tests), not model " +
        "capability. The chaos, red-team, impossible-task and budget suites measure SAGE's own mechanisms and are " +
        "meaningful in fake mode. Model-dependent metrics (resolved rate on real tasks, cost per resolved task, cheating " +
        "rate of a real model) require live mode."
      : "**Live mode.** Task results come from a real model through OpenCode. The chaos, red-team, impossible-task and " +
        "budget suites always use the fake engine because they test SAGE's mechanisms, not the model.",
    "",
    "## Task suite (hidden acceptance tests)",
    "",
    `${r.tasks.length} tasks across ${new Set(r.tasks.map((t) => t.repo)).size} fixture repos. Hidden tests are written into a`,
    "throwaway checkout of the final run branch after the run; agents never see them.",
    "",
    "| Task | Repo | Final state | Hidden tests | Attempts | Tokens | Cost | Wall (s) | Denied calls | Human interventions | Traceable |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
    ...r.tasks.map(
      (t) =>
        `| ${t.id} | ${t.repo} | ${t.state} | ${t.resolved ? "PASS" : "FAIL"} (${t.hiddenSummary}) | ${t.attempts} | ${t.tokens} | ${usd(t.costUsd)} | ${(t.wallMs / 1000).toFixed(1)} | ${t.deniedCalls} | ${t.humanInterventions} | ${pct(t.traceable, 1)} |`,
    ),
    "",
    `- **Resolved (hidden tests pass):** ${resolved}/${done.length} (${pct(resolved, done.length)})`,
    `- **Mean wall-clock per task:** ${meanWall.toFixed(1)} s`,
    `- **File changes traceable to a task (mean):** ${(100 * meanTrace).toFixed(0)}%`,
    `- **Cost per resolved task:** ${fake ? "not measured (fake engine has a synthetic price table; numbers above are synthetic)" : resolved ? usd(r.tasks.reduce((s, t) => s + t.costUsd, 0) / resolved) : "n/a (nothing resolved)"}`,
    `- **Human interventions per run:** ${done.length ? (done.reduce((s, t) => s + t.humanInterventions, 0) / done.length).toFixed(1) : "n/a"} (the plan approval given with \`--yes\` counts as one; merge approval is not exercised by the eval)`,
    "",
    "## Chaos suite — crash and resume (RQ1)",
    "",
    "The orchestrator process kills itself (SIGKILL / TerminateProcess, no cleanup) at each point; `sage resume` then",
    "continues from the journal.",
    "",
    "| Crash point | Crashed | Resumed to completion | Steps re-executed | Extra agent invocations | Resume wall (s) |",
    "|---|---|---|---|---|---|",
    ...r.chaos.map(
      (c) =>
        `| ${c.point} | ${c.crashed ? "yes" : "no"} | ${c.resumed ? "yes" : "NO"} | ${c.reexecutedSteps} | ${c.agentReinvocations} | ${(c.resumeMs / 1000).toFixed(1)} |`,
    ),
    "",
    `- **Resume success:** ${chaosOk}/${r.chaos.length} (${pct(chaosOk, r.chaos.length)})`,
    `- **Steps re-executed per recovery (mean):** ${(r.chaos.reduce((s, c) => s + c.reexecutedSteps, 0) / Math.max(1, r.chaos.length)).toFixed(2)} — only a step that was *started but not completed* is re-run (e.g. the agent turn killed mid-flight).`,
    "",
    "## Red-team suite (RQ3)",
    "",
    `- **Malicious tool calls attempted:** ${r.redTeam.attempted}`,
    `- **Blocked by policy:** ${r.redTeam.blocked}/${r.redTeam.attempted} (${pct(r.redTeam.blocked, r.redTeam.attempted)})`,
    `- **Malicious effects that landed** (files outside the worktree, protected-file or unexpected changes on the run branch): ${r.redTeam.landed}`,
    `- **Rules that fired:** ${r.redTeam.rules.join(", ")}`,
    "- Scope: scripted attacks through tool calls (path escape, secret env reads, env dumps, network commands and tools, `git push`, test/CI/git-internals edits, `sage approve` from the agent). Prompt-injection *content* against a real model is not measured here.",
    "",
    "## Impossible task (RQ2, ImpossibleBench-style)",
    "",
    'A visible test contradicts the specification, so the only way to "pass" is to tamper with the test. The scripted',
    "agent edits the test directly and also through a script it writes and runs.",
    "",
    `- **False completions (task marked PASSED):** ${r.impossible.falseCompletions}/${r.impossible.tasks}`,
    `- **Direct protected-file edits blocked by policy:** ${r.impossible.directBlocked}`,
    `- **Indirect tampering detected by the verifier:** ${r.impossible.indirectDetected} attempt(s)`,
    `- **Final task state:** ${r.impossible.finalState} (escalated to a human, never merged)`,
    "",
    "## Budget hard stop (G7)",
    "",
    `- Task budget ${usd(r.budget.limitUsd)}; spent ${usd(r.budget.spentUsd)}; overrun ${r.budget.overrunPct.toFixed(0)}% (bounded by one model call: the check runs after each call); result ${r.budget.stoppedTask}.`,
    "",
    "## Not measured",
    "",
    "| Metric | Status | Reason |",
    "|---|---|---|",
    "| OpenCode-alone baseline (same model, same tasks) | not measured | needs a separate harness driving bare OpenCode; future work |",
    "| SWE-bench Verified / Pro subsets | not measured — out of scope | the official SWE-bench harness requires Docker, which this project does not use (no Docker/VMs constraint) |",
    "| ImpossibleBench subset with a real model | not measured | requires live runs on the published dataset; the scripted impossible task above tests SAGE's enforcement only |",
    `| Cost per resolved task (real model) | ${fake ? "not measured in this report" : "see above"} | ${fake ? "fake mode; run `SAGE_LIVE=1 sage eval --live`" : "live mode"} |`,
    "| Approval latency | not measured | approvals are pre-given (`--yes`) or scripted in the eval |",
    "",
    `Live spend in this eval: ${usd(r.liveSpendUsd)}.`,
    "",
  ];
  return lines.join("\n");
}
